export type UxKey = keyof typeof TABLE.zh

/** The zh or en table a locale reads (anything not Chinese reads English). */
export function uxLang(locale: string): 'zh' | 'en' {
  return /^zh\b/i.test(locale || '') ? 'zh' : 'en'
}

/** One Kailo string with `{name}` parameters filled in. */
export function ux(key: UxKey, locale: string, params: Record<string, string | number> = {}): string {
  const text: string = TABLE[uxLang(locale)][key] ?? TABLE.zh[key]
  return text.replace(/\{(\w+)\}/g, (match, name: string) => (name in params ? String(params[name]) : match))
}

/** Every entry of both tables (for the wording test). */
export function uxEntries(): Array<[lang: 'zh' | 'en', key: string, text: string]> {
  const out: Array<['zh' | 'en', string, string]> = []
  for (const lang of ['zh', 'en'] as const) for (const [key, text] of Object.entries(TABLE[lang])) out.push([lang, key, text])
  return out
}

/** DD-165 refusal decisions with a Kailo notice. */
export const QUOTA_DECISIONS = ['TENANT_QUOTA_EXHAUSTED', 'MEMBER_QUOTA_EXHAUSTED', 'QUOTA_NOT_CONFIGURED', 'DEPENDENCY_UNAVAILABLE'] as const
export type QuotaDecision = typeof QUOTA_DECISIONS[number]

export function isQuotaDecision(value: unknown): value is QuotaDecision {
  return typeof value === 'string' && (QUOTA_DECISIONS as readonly string[]).includes(value)
}

/** The notice for a refused question in the page's current language. */
export function quotaNotice(decision: QuotaDecision, locale: string): string {
  return ux(`quota.${decision}` as UxKey, locale)
}
