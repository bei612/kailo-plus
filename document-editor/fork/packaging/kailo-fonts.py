"""Bring the Kailo UI font into the editor chrome (DD-132(7)③).

The Kailo font stack is the token `--kailo-font-sans` of the Kailo token package
(client-kit/embed/kailo-theme-tokens.css); its first family is the variable Inter
face the web client ships from @fontsource-variable/inter, locked with its
integrity in web-client/web/package-lock.json. This script takes exactly that
locked package (downloaded from the lock's `resolved` URL and verified against the
lock's sha512 integrity), and writes

  OUTPUT_DIR/kailo-font.less        @font-face rules of the package's wght.css
                                    with urls under web-apps' common resources,
                                    and `:root { --font-family-base: <stack> }`
  OUTPUT_DIR/fonts/kailo/*.woff2    the faces those rules reference
  OUTPUT_DIR/fonts/kailo/LICENSE    the package's font license (SIL OFL 1.1)

web-apps' colors-table.less imports kailo-font.less after its own `:root`
defaults, so every editor UI element using @font-family-base (variables.less)
takes the Kailo stack; the document content is drawn by sdkjs with the
document's own fonts and is not affected.

  python3 kailo-fonts.py PACKAGE_LOCK TOKENS_CSS OUTPUT_DIR
"""
import base64
import hashlib
import io
import json
import os
import re
import sys
import tarfile
import time
import urllib.request

PACKAGE = "@fontsource-variable/inter"
REGISTRY = "https://registry.npmjs.org/"
STYLESHEET = "package/wght.css"
LICENSE = "package/LICENSE"
# web-apps' url base of its common resources (Gruntfile less modifyVars of
# every app bundle); the fonts sit beside the common img directory.
FONT_URL = "@{common-image-const-path}/../fonts/kailo/"
FONT_SANS = re.compile(r"--kailo-font-sans:\s*([^;]+);")
FACE = re.compile(r"@font-face\s*\{([^}]*)\}")


class Refused(Exception):
    pass


def locked(lock_text):
    """resolved URL and sha512 digest of the locked font package."""
    entry = json.loads(lock_text).get("packages", {}).get("node_modules/" + PACKAGE)
    if not entry:
        raise Refused(PACKAGE + " is not in the package lock")
    resolved, integrity = entry.get("resolved", ""), entry.get("integrity", "")
    version = entry.get("version", "")
    if not re.fullmatch(r"[0-9]+\.[0-9]+\.[0-9]+", version) \
            or resolved != REGISTRY + PACKAGE + "/-/inter-" + version + ".tgz":
        raise Refused("unexpected locked source " + resolved)
    if not integrity.startswith("sha512-"):
        raise Refused("the lock must carry a sha512 integrity")
    return resolved, base64.b64decode(integrity[len("sha512-"):], validate=True)


def verified(data, digest):
    if hashlib.sha512(data).digest() != digest:
        raise Refused("downloaded package does not match the lock integrity")
    return data


def font_stack(css):
    """The `--kailo-font-sans` value of the token package (one value for all modes)."""
    values = {v.strip() for v in FONT_SANS.findall(css)}
    if len(values) != 1:
        raise Refused("token file must define --kailo-font-sans exactly once")
    stack = values.pop()
    if not re.fullmatch(r"[A-Za-z0-9 ,\"'-]+", stack):
        raise Refused("unexpected characters in --kailo-font-sans")
    return stack


def faces(stylesheet, stack):
    """(less source, referenced file names) from the package's wght.css."""
    first = stack.split(",")[0].strip().strip("\"'")
    rules, files = [], []
    for body in FACE.findall(stylesheet):
        declared = re.search(r"font-family:\s*'([^']+)'", body)
        source = re.search(r"src:\s*url\(\./files/([a-z0-9-]+\.woff2)\)\s*format\('([a-z0-9-]+)'\)", body)
        weight = re.search(r"font-weight:\s*([0-9 ]+);", body)
        ranges = re.search(r"unicode-range:\s*([U+0-9A-Fa-f,\-]+);", body)
        if not (declared and source and weight and ranges):
            raise Refused("unexpected @font-face in " + STYLESHEET)
        if declared.group(1) != first:
            raise Refused("the package declares '" + declared.group(1) + "', the token stack starts with '" + first + "'")
        files.append(source.group(1))
        rules.append(
            "@font-face {\n"
            "  font-family: '" + first + "';\n"
            "  font-style: normal;\n"
            "  font-display: swap;\n"
            "  font-weight: " + weight.group(1).strip() + ";\n"
            "  src: ~\"url('" + FONT_URL + source.group(1) + "') format('" + source.group(2) + "')\";\n"
            "  unicode-range: " + ranges.group(1) + ";\n"
            "}\n")
    if not rules:
        raise Refused(STYLESHEET + " declares no faces")
    less = ("// Generated by kailo-fonts.py (DD-132(7)③) from " + PACKAGE + " and the Kailo token package.\n"
            + "\n".join(rules)
            + "\n:root {\n  --font-family-base: " + stack + ";\n}\n")
    return less, files


def write(output, archive, stack):
    with tarfile.open(fileobj=io.BytesIO(archive), mode="r:gz") as tar:
        def member(name):
            item = tar.getmember(name)
            if not item.isfile():
                raise Refused(name + " is not a regular file")
            return tar.extractfile(item).read()
        less, files = faces(member(STYLESHEET).decode("utf-8"), stack)
        target = os.path.join(output, "fonts", "kailo")
        os.makedirs(target, exist_ok=True)
        for name in files + ["LICENSE"]:
            data = member("package/files/" + name if name != "LICENSE" else LICENSE)
            with open(os.path.join(target, name), "wb") as stream:
                stream.write(data)
    with open(os.path.join(output, "kailo-font.less"), "w", encoding="utf-8") as stream:
        stream.write(less)
    return files


def download(url):
    for attempt in range(4):
        try:
            with urllib.request.urlopen(url, timeout=60) as response:
                return response.read()
        except OSError:
            if attempt == 3:
                raise
            time.sleep(2 ** attempt)


def main(argv):
    if len(argv) != 3:
        print("usage: kailo-fonts.py PACKAGE_LOCK TOKENS_CSS OUTPUT_DIR", file=sys.stderr)
        return 2
    with open(argv[0], encoding="utf-8") as stream:
        url, digest = locked(stream.read())
    with open(argv[1], encoding="utf-8") as stream:
        stack = font_stack(stream.read())
    files = write(argv[2], verified(download(url), digest), stack)
    print("kailo font: " + stack + " (" + str(len(files)) + " faces)")
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main(sys.argv[1:]))
    except Refused as error:
        print("kailo font refused: " + str(error), file=sys.stderr)
        sys.exit(2)
