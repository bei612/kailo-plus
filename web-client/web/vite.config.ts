/// <reference types="vitest/config" />
import { tanstackRouter } from "@tanstack/router-plugin/vite";
import react from "@vitejs/plugin-react";
import { readFileSync } from "node:fs";
import { defineConfig } from "vite";
import { profileAssets } from "../../client-kit/ts/platform/profile-assets.ts";

// Original Settings footer `v{appVersion}`: the browser host reports its own package version.
const webVersion = (JSON.parse(readFileSync(new URL("./package.json", import.meta.url), "utf8")) as { version: string }).version;

// https://vite.dev/config/
export default defineConfig({
  base: process.env.VITE_BASE_PATH || "/",
  define: {
    __BUZZ_WEB_VERSION__: JSON.stringify(webVersion),
  },
  plugins: [
    profileAssets(import.meta.url),
    {
      name: "deployed-platform-build-info",
      apply: "build",
      generateBundle() {
        const buildId = process.env.PLATFORM_BUILD_ID;
        if (!buildId || !/^sha256:[a-f0-9]{64}$/.test(buildId)) {
          this.error("PLATFORM_BUILD_ID must come from the original source manifest");
        }
        this.emitFile({
          type: "asset", fileName: "platform-build-info.json",
          source: JSON.stringify({
            subject: "BUZZ_WEB", buildId, hostApiVersion: "NONE",
            adapterProtocolVersions: [], driverRegistryKeys: [], platformPortKeys: [],
            reportedAt: new Date().toISOString(),
          }),
        });
      },
    },
    tanstackRouter({
      target: "react",
      routesDirectory: "./src/app/routes",
      generatedRouteTree: "./src/app/routeTree.gen.ts",
      virtualRouteConfig: "./src/app/routes.ts",
      quoteStyle: "double",
      semicolons: true,
      routeTreeFileHeader: ["// biome-ignore-all lint: generated by TanStack Router"],
    }),
    react(),
  ],
  resolve: {
    alias: {
      "@": "/src",
    },
    // One React for the shell and every client-kit source module, wherever a test imports it
    // from (installed copy or repository path); the image build already has a single copy.
    dedupe: ["react", "react-dom"],
  },
  server: {
    port: parseInt(process.env.VITE_PORT || "5173", 10),
    strictPort: true,
  },
  test: {
    // client-kit ships TypeScript source installed as file: copies (.npmrc install-links).
    // The production build bundles it; vitest must transform it the same way instead of
    // externalizing node_modules to Node, which cannot strip types there.
    server: { deps: { inline: [/[\\/]@client-kit[\\/]/] } },
  },
});
