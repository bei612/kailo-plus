"""Render data-query/docker/native-gateway.yaml (DD-133 §2).

The public /kailo-embed/ page of the native Gateway is kept as a readable
script (bootstrap.js, next to this file) and rendered into the static
Gateway configuration together with its CSP hash.

  python3 -I render.py            rewrite ../native-gateway.yaml
  python3 -I render.py --check    exit 1 if ../native-gateway.yaml differs
"""
import base64, hashlib, os, sys, textwrap
here = os.path.dirname(os.path.abspath(__file__))
script_path = os.path.join(here, 'bootstrap.js')
out_path = os.path.join(here, '..', 'native-gateway.yaml')
script = open(script_path, encoding='utf-8').read().strip('\n')
assert '$' not in script, 'shellexpand would rewrite $ in the gateway configuration'
inline = '\n' + script + '\n'
digest = base64.b64encode(hashlib.sha256(inline.encode()).digest()).decode()
style = ("body{margin:0;min-height:100vh;display:flex;align-items:center;justify-content:center;"
         "font:14px/1.6 var(--kailo-font-sans,system-ui,-apple-system,'PingFang SC','Microsoft YaHei',sans-serif);"
         "color:#4b5563;background:transparent}#m{display:none;text-align:center;padding:24px}"
         "#l{display:inline-block;margin-top:12px;padding:6px 16px;border-radius:6px;background:#111827;color:#fff;text-decoration:none}"
         "html[data-kailo-theme=dark] body{color:#d1d5db;background:#1f2328}"
         "html[data-kailo-theme=dark] #l{background:#f3f4f6;color:#111827}")
html = ('<!doctype html>\n<html lang="zh-CN">\n<head>\n<meta charset="utf-8">\n'
        '<meta name="viewport" content="width=device-width,initial-scale=1">\n'
        '<meta name="kailo-web-origin" content="${KAILO_FRAME_ANCESTORS}">\n'
        '<meta name="kailo-logout-url" content="${KAILO_LOGOUT_URL}">\n'
        '<title></title>\n<style>' + style + '</style>\n</head>\n<body>\n'
        '<div id="m"><div id="t"></div><a id="l" target="_top" href="/"></a></div>\n'
        '<script>' + inline + '</script>\n</body>\n</html>\n')
csp = ("default-src 'none'; script-src 'sha256-" + digest + "'; style-src 'unsafe-inline'; "
       "frame-src 'self' ${WREN_OIDC_ISSUER}/; base-uri 'none'; form-action 'none'; frame-ancestors 'self' ${KAILO_FRAME_ANCESTORS}")
def cel(value):
    assert '"' not in value and '\\' not in value
    return "'" + ('"' + value + '"').replace("'", "''") + "'"
body = textwrap.indent(html, ' ' * 18)
yaml_text = f"""# SS-WRN-IDENTITY: this is the native service's dedicated browser gateway,
# not the platform's dynamic Tool/ModelRoute gateway configuration.
# OIDC creates its own encrypted HttpOnly browser cookie. Only its verified
# component-specific ID token is forwarded on the private backend hop.
#
# DD-133(2)/(6) (`.design/07` §4.7.2, §4.7.5). The OIDC policy is attached
# to the native UI route instead of the listener so that one static,
# credential-free page can be served before authentication:
#   /kailo-embed/signin      login.redirect target. At top level it continues
#                            to /auth/login. Inside the Kailo iframe it first
#                            tries the existing IdP session in a hidden
#                            same-origin frame (the IdP login page refuses to be
#                            framed, so a missing session is detected without
#                            ever showing it); when that fails it sends wire v1
#                            {{source:"kailo-embed",version:1,type:"auth-required"}}
#                            to the exact kailo-web-origin and Kailo signs in at
#                            top level on the user's click.
#   /kailo-embed/auth-ok     landing page of that hidden attempt.
#   /kailo-embed/signed-out  logout.redirect target; at top level it continues
#                            to KAILO_LOGOUT_URL (the Kailo sign-out) when set.
# /oauth/backchannel-logout receives the IdP's signed logout_token (form POST,
# server to server) and ends that sid's (or that subject's) Gateway sessions.
# The page receives no identity, cookie or upstream response. Its only script is
# pinned by the CSP hash below; the configuration loader expands $-variables,
# so the script deliberately contains no dollar sign.
#
# Generated by kailo-embed/render.py from kailo-embed/bootstrap.js; edit those.
config:
  adminAddr: 127.0.0.1:${{WREN_GATEWAY_ADMIN_PORT}}
binds:
  - port: ${{WREN_GATEWAY_HTTP_PORT}}
    listeners:
      - name: wren-native-browser
        protocol: HTTP
        routes:
          - name: kailo-embed-page
            matches:
              - path:
                  pathPrefix: /kailo-embed/
            policies:
              directResponse:
                status: 200
                headers:
                  content-type: {cel('text/html; charset=utf-8')}
                  cache-control: {cel('no-store')}
                  x-content-type-options: {cel('nosniff')}
                  referrer-policy: {cel('strict-origin-when-cross-origin')}
                  content-security-policy: {cel(csp)}
                body: |
{body.rstrip()}
          - name: native-ui
            matches:
              - path:
                  pathPrefix: /
            policies:
              oidc:
                issuer: ${{WREN_OIDC_ISSUER}}
                clientId: ${{WREN_OIDC_CLIENT_ID}}
                clientSecret: ${{WREN_OIDC_CLIENT_SECRET}}
                redirectURI: ${{WREN_OIDC_REDIRECT_URI}}
                # DD-133 §3: display name, avatar, e-mail and locale come from
                # the same IdP claims on every login.
                scopes: [profile, email]
                login:
                  path: /auth/login
                  redirect: /kailo-embed/signin
                logout:
                  path: /auth/logout
                  redirect: /kailo-embed/signed-out
                # DD-133(6): register <public origin>/oauth/backchannel-logout
                # as this client's back-channel logout URL (session required).
                backchannelLogout:
                  path: /oauth/backchannel-logout
              # Browser credentials and platform identity headers never reach
              # the native UI. This runs on the route, after the OIDC policy
              # above has read its own transaction and session cookies: listener
              # policies run before route policies, so stripping Cookie there
              # leaves the route OIDC without them ("missing transaction").
              transformations:
                request:
                  remove:
                    - authorization
                    - cookie
                    - proxy-authorization
                    - x-platform-oidc-issuer
                    - x-platform-oidc-subject
                    - x-platform-tenant
                    - x-platform-workspace
                    - x-platform-principal
              # The pinned Gateway exposes CSRF on routes, not listener policy.
              # This catch-all covers every native UI write with no extra origin.
              csrf: {{}}
              backendAuth:
                passthrough: {{}}
            backends:
              - host: ${{WREN_UI_UPSTREAM}}
"""
if '--check' in sys.argv[1:]:
    current = open(out_path, encoding='utf-8').read()
    if current != yaml_text:
        print('native-gateway.yaml is not the rendering of kailo-embed/bootstrap.js', file=sys.stderr)
        sys.exit(1)
    print('native-gateway.yaml matches kailo-embed/bootstrap.js (script sha256-' + digest + ')')
else:
    open(out_path, 'w', encoding='utf-8').write(yaml_text)
    print('sha256-' + digest)
